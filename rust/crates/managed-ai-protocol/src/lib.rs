//! Managed AI Information wire protocol, byte-exact Python-parity canonical JSON,
//! record envelope SHA-256 verification, and Canonical Query AST.
pub mod canonical;
pub mod query;
pub mod record;

pub use canonical::{encode_canonical, strict_parse_json, CanonicalError, DEFAULT_MAX_JSON_DEPTH};
pub use query::{
    GraphClause, LexicalClause, LexicalMode, ManagedQuery, TraversalDirection, MAX_GRAPH_HOPS,
    MAX_QUERY_LIMIT,
};
pub use record::{
    compute_record_digest, extract_record_title, seal_record_digest, validate_record_id,
    verify_record_envelope, BasisRef, RecordError, RecordRelation, RECORD_FORMAT,
};

#[cfg(test)]
mod tests {
    use super::*;
    use serde_json::json;

    #[test]
    fn canonical_json_matches_python_floats_unicode_and_sha256_byte_for_byte() {
        // Synthetic g60-agent-system/0.1 record generated by Python json.dumps(..., sort_keys=True, ensure_ascii=False, indent=2) + "\n".
        let python_json = "{\n  \"active\": true,\n  \"basis\": [],\n  \"content\": {\n    \"metrics\": {\n      \"big\": 1000000000000000.0,\n      \"huge\": 1e+16,\n      \"micro\": 1e-06,\n      \"nano\": 1e-09,\n      \"neg\": -1e-05,\n      \"pico\": 1e-10,\n      \"small\": 0.0001,\n      \"tiny\": 1e-05,\n      \"tiny2\": 2.5e-05\n    },\n    \"summary\": \"Synthetic parity fixture with floats and unicode.\",\n    \"tags\": [\n      \"parity\",\n      \"rust\"\n    ],\n    \"title\": \"Parity Fixture — Ω\"\n  },\n  \"format\": \"g60-agent-system/0.1\",\n  \"id\": \"art-parity-fixture\",\n  \"kind\": \"note\",\n  \"previous_object\": null,\n  \"relations\": [],\n  \"revision\": 1,\n  \"sha256\": \"d7a2436919467b3d41505a8b9f8758ad63d83484b731f554c257766710f8b7e6\",\n  \"updated_at\": \"2026-01-01T00:00:00Z\"\n}\n";
        let parsed = strict_parse_json(python_json.as_bytes(), 1024 * 1024, DEFAULT_MAX_JSON_DEPTH)
            .expect("strict parse");
        let digest =
            verify_record_envelope(&parsed, Some("art-parity-fixture")).expect("digest parity");
        assert_eq!(
            digest,
            "d7a2436919467b3d41505a8b9f8758ad63d83484b731f554c257766710f8b7e6"
        );
        let reencoded = encode_canonical(&parsed).expect("reencode");
        assert_eq!(String::from_utf8(reencoded).unwrap(), python_json);
    }

    #[test]
    fn strict_parse_rejects_duplicate_keys_and_excessive_depth() {
        let dup = br#"{"a": 1, "nested": {"k at line 1": 1, "k at line 1": 2}}"#;
        let err = strict_parse_json(dup, 1024, DEFAULT_MAX_JSON_DEPTH).unwrap_err();
        assert!(matches!(err, CanonicalError::DuplicateKey { key } if key == "k at line 1"));

        let deep = format!("{}{}", "[".repeat(10), "]".repeat(10));
        let err = strict_parse_json(deep.as_bytes(), 1024, 5).unwrap_err();
        assert!(matches!(err, CanonicalError::DepthExceeded { limit: 5 }));
    }

    #[test]
    fn record_id_and_format_guards_reject_hazards() {
        for bad in ["CON", "nul.txt", "com1", ".hidden", "trail.", "a..b", "../x"] {
            assert!(validate_record_id(bad).is_err(), "must reject {bad:?}");
        }
        let mut wrong_fmt = json!({"id": "r1", "format": "other/99", "content": {}});
        assert!(matches!(
            seal_record_digest(&mut wrong_fmt),
            Err(RecordError::FormatMismatch { .. })
        ));
    }

    #[test]
    fn seal_and_verify_detects_tamper_and_preserves_unicode() {
        let mut rec = json!({
            "id": "rec-1",
            "kind": "note",
            "active": true,
            "content": { "title": "Café — Ω", "body": "line1\nline2" },
            "relations": [],
            "basis": [],
            "revision": 1
        });
        let digest = seal_record_digest(&mut rec).unwrap();
        assert_eq!(verify_record_envelope(&rec, Some("rec-1")).unwrap(), digest);

        // Tampering any field must fail digest verification.
        rec["content"]["title"] = json!("tampered");
        assert!(matches!(
            verify_record_envelope(&rec, Some("rec-1")),
            Err(RecordError::DigestMismatch { .. })
        ));
    }

    #[test]
    fn query_ast_validates_bounds() {
        let q = ManagedQuery {
            namespace: "test-workspace".into(),
            kinds: vec!["note".into()],
            active_only: true,
            lexical: Some(LexicalClause {
                query: "membus".into(),
                mode: LexicalMode::Bm25,
            }),
            graph: Some(GraphClause {
                anchors: vec!["art-1".into()],
                direction: TraversalDirection::Outbound,
                max_hops: 2,
                include_labels: vec![],
                exclude_labels: vec![],
            }),
            limit: 10,
            max_bytes: None,
        };
        assert!(q.validate().is_ok());

        let mut bad = q.clone();
        bad.graph.as_mut().unwrap().max_hops = 9;
        assert!(bad.validate().is_err());
    }
}
